// Helper to generate simulated candles around a base price
function generateCandles(basePrice: number, count: number, volatility: number): {
  '1m': any[];
  '5m': any[];
  '15m': any[];
  '1H': any[];
  'D': any[];
  'W': any[];
} {
  const timeframes = ['1m', '5m', '15m', '1H', 'D', 'W'] as const;
  const result: any = {};

  timeframes.forEach((tf) => {
    const candles = [];
    let currentPrice = basePrice * (1 - volatility * (count / 2) * 0.1);
    for (let i = 0; i < count; i++) {
      const delta = (Math.random() - 0.44) * (basePrice * volatility);
      const open = Math.round(currentPrice * 100) / 100;
      const close = Math.round((open + delta) * 100) / 100;
      const high = Math.round((Math.max(open, close) + Math.random() * (basePrice * volatility * 0.5)) * 100) / 100;
      const low = Math.round((Math.min(open, close) - Math.random() * (basePrice * volatility * 0.5)) * 100) / 100;
      const volume = Math.floor(Math.random() * 8000000 + 2000000);
      
      let timeLabel = '';
      if (tf === '1m') timeLabel = `${15 + Math.floor(i / 60)}:${String(i % 60).padStart(2, '0')}`;
      else if (tf === '5m') timeLabel = `${10 + Math.floor(i / 12)}:${String((i * 5) % 60).padStart(2, '0')}`;
      else if (tf === '15m') timeLabel = `${9 + Math.floor(i / 4)}:${String((i * 15) % 60).padStart(2, '0')}`;
      else if (tf === '1H') timeLabel = `${9 + i}:00`;
      else if (tf === 'D') timeLabel = `Day ${i + 1}`;
      else timeLabel = `Wk ${i + 1}`;

      candles.push({
        time: timeLabel,
        open,
        high,
        low,
        close,
        volume,
      });
      currentPrice = close;
    }
    result[tf] = candles;
  });

  return result;
}

